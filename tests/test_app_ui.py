"""End-to-end UI tests using Streamlit's AppTest (runs the real app headlessly)."""
from pathlib import Path

import pytest
from streamlit.testing.v1 import AppTest

APP = str(Path(__file__).resolve().parent.parent / "app.py")
PAGES = ["Dashboard", "Project Input", "Lifecycle Mapping (U1)", "Risk Register (U2)", "NIST Guidance (U3)",
         "Heatmap & Assessment (U4)", "RMF Classification (U5)", "About"]


def fresh():
    return AppTest.from_file(APP, default_timeout=180).run()


@pytest.mark.parametrize("sample_index", [0, 1])
def test_load_each_sample_and_open_every_page(sample_index):
    at = fresh()
    at.sidebar.selectbox[0].set_value(at.sidebar.selectbox[0].options[sample_index])
    at.sidebar.button(key="load_sample").click().run()
    assert not at.exception
    assert len(at.session_state["register"]) == 16
    for p in PAGES:
        at.sidebar.radio[0].set_value(p).run()
        assert not at.exception, f"exception on page {p}: {[e.value for e in at.exception]}"


def test_pages_without_register_show_guidance_not_crash():
    at = fresh()
    for p in PAGES[2:7]:
        at.sidebar.radio[0].set_value(p).run()
        assert not at.exception
        assert any("No risk register yet" in i.value for i in at.info)


def test_generate_with_fallback_is_labelled_not_llm(monkeypatch):
    monkeypatch.delenv("GEMINI_API_KEY", raising=False)
    monkeypatch.delenv("GROQ_API_KEY", raising=False)
    at = fresh()
    at.sidebar.radio[0].set_value("Project Input").run()
    at.text_area[0].set_value("An AI system that predicts crop disease from leaf photos for farmers.")
    at.button[0].click().run()   # the form's submit button
    assert not at.exception
    assert at.session_state["register"] is not None
    assert "not LLM" in at.session_state["source_label"]
    assert (at.session_state["register"]["Generated By"] == at.session_state["source_label"]).all()


def test_empty_description_is_rejected():
    at = fresh()
    at.sidebar.radio[0].set_value("Project Input").run()
    at.button[0].click().run()
    assert any("project description" in e.value.lower() for e in at.error)
    assert at.session_state["register"] is None
