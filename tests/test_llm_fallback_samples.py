"""Tests for U2 (LLM parsing + labelled fallback) and the two sample projects.

No real LLM API call is made in these tests (that needs a private key and network).
They test the parsing/validation code and the honesty of the labels.
"""
import json

import pytest

from modules import llm_client
from modules.config import REGISTER_COLUMNS, RISK_CATEGORIES
from modules.fallback import FALLBACK_LABEL, detect_domain, generate_fallback_risks
from modules.llm_client import LLMError, _extract_json, generate_risks_with_llm, risks_to_dataframe
from modules.samples import SAMPLE_LABEL, load_sample, sample_register

RAW = [{"title": "Bias", "description": "d", "lifecycle_stage": "data prep", "risk_category": "fairness and bias",
        "likelihood": 4, "impact": "5", "mitigation": "m", "stakeholder": "DS"},
       {"title": "Odd", "description": "d", "lifecycle_stage": "???", "risk_category": "Nonsense",
        "likelihood": 99, "impact": 0, "mitigation": "", "stakeholder": "PM"}]


def test_extract_json_handles_code_fences_and_prose():
    text = "Here you go:\n```json\n" + json.dumps(RAW) + "\n```\nHope it helps"
    assert len(_extract_json(text)) == 2


def test_extract_json_rejects_garbage():
    with pytest.raises(LLMError):
        _extract_json("no json here")
    with pytest.raises(LLMError):
        _extract_json("[not valid json]")


def test_llm_rows_are_validated_and_scored():
    df = risks_to_dataframe(RAW, "LLM - test")
    assert list(df["Risk ID"]) == ["R01", "R02"]
    assert df.loc[0, "Lifecycle Stage"] == "Data Preparation"
    assert df.loc[0, "Risk Category"] == "Fairness and Bias"
    assert df.loc[0, "Risk Score"] == 20 and df.loc[0, "Severity"] == "Critical"
    assert df.loc[1, "Risk Category"] in RISK_CATEGORIES      # invalid category coerced
    assert df.loc[1, "Likelihood"] == 5 and df.loc[1, "Impact"] == 1  # clamped


def test_empty_llm_output_raises():
    with pytest.raises(LLMError):
        risks_to_dataframe([], "LLM - test")


def test_no_api_key_raises_instead_of_pretending(monkeypatch):
    monkeypatch.delenv("GEMINI_API_KEY", raising=False)
    monkeypatch.delenv("GROQ_API_KEY", raising=False)
    monkeypatch.setattr(llm_client, "get_secret", lambda name: None)
    assert llm_client.available_provider() is None
    with pytest.raises(LLMError):
        generate_risks_with_llm({"name": "x", "description": "y"})


def test_mocked_llm_response_is_labelled_as_llm(monkeypatch):
    monkeypatch.setattr(llm_client, "get_secret", lambda name: "fake" if name == "GEMINI_API_KEY" else None)
    monkeypatch.setattr(llm_client, "_call_gemini", lambda prompt: (json.dumps(RAW), "Gemini (mock-model)"))
    df, label = generate_risks_with_llm({"name": "x", "description": "y"})
    assert label.startswith("LLM") and (df["Generated By"] == label).all()


def test_fallback_is_always_labelled_not_llm():
    df = generate_fallback_risks({"name": "Smart Farming AI", "description": "predicts crop yield"}, 10)
    assert (df["Generated By"] == FALLBACK_LABEL).all()
    assert "not LLM" in FALLBACK_LABEL
    assert len(df) >= 8 and df["Lifecycle Stage"].nunique() == 8


def test_fallback_domain_detection_and_generic_naming():
    assert detect_domain({"description": "diagnosis of patient disease in hospital"}) == "healthcare"
    assert detect_domain({"description": "resume screening for job candidates"}) == "recruitment"
    assert detect_domain({"description": "route optimisation for delivery trucks"}) == "generic"
    df = generate_fallback_risks({"name": "RouteBot", "description": "delivery trucks"}, 10)
    assert df["Description"].str.contains("RouteBot").any()


@pytest.mark.parametrize("key,must_cover", [
    ("healthcare_diagnosis", ["bias", "privacy", "explain", "drift", "cyber", "oversight", "incorrect"]),
    ("recruitment_screening", ["bias", "ranking", "privacy", "rejection", "opaque", "security", "oversight"]),
])
def test_sample_topics_are_covered(key, must_cover):
    blob = " ".join(r["title"] + " " + r["description"] for r in load_sample(key)["risks"]).lower()
    for topic in must_cover:
        assert topic in blob, f"{key} missing topic: {topic}"


@pytest.mark.parametrize("key", ["healthcare_diagnosis", "recruitment_screening"])
def test_sample_register_structure(key):
    df = sample_register(key)
    assert len(df) >= 15
    assert set(REGISTER_COLUMNS).issubset(df.columns)
    assert df["Risk ID"].is_unique
    assert (df["Generated By"] == SAMPLE_LABEL).all()           # honest label: not LLM
    assert (df["Mitigation Strategy"].str.len() > 10).all()
    assert (df["Responsible Stakeholder"].str.len() > 2).all()
