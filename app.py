# ----------------------------------------------------------------------------- helpers
def metric_card(label, value, sub="", color="#1F2A44"):
    st.markdown(
        f'<div class="card"><div class="label">{label}</div>'
        f'<div class="value" style="color:{color}">{value}</div><div class="sub">{sub}</div></div>',
        unsafe_allow_html=True,
    )


def badge(text, color):
    return f'<span class="badge" style="background:{color}">{text}</span>'


def header(title, subtitle):
    st.markdown(f'<div class="hero"><h1>{title}</h1><p>{subtitle}</p></div>', unsafe_allow_html=True)


def source_banner():
    src = st.session_state.get("source_label")
    if not src:
        return
    if src.startswith("LLM"):
        st.markdown(f'<div class="src"><b>Generated by:</b> {src}</div>', unsafe_allow_html=True)
    elif src.startswith("Curated"):
        st.markdown(f'<div class="src"><b>Source:</b> {src}. These risks were written by hand for the demo, '
                    f'<b>not</b> produced by an LLM.</div>', unsafe_allow_html=True)
    else:
        st.markdown(f'<div class="src warn"><b>Source: {src}.</b> No LLM was used. Rows come from pre-written '
                    f'templates chosen by simple domain detection.</div>', unsafe_allow_html=True)


def register_hash(df: pd.DataFrame) -> str:
    return hashlib.md5((df["Title"] + df["Description"]).str.cat(sep="|").encode("utf-8")).hexdigest()


@st.cache_resource(show_spinner="Loading Sentence-BERT model (first run downloads about 90 MB)...")
def get_retriever():
    """Cached so the model loads once per server. Returns (retriever, error_message)."""
    try:
        return NISTRetriever(), None
    except ModelUnavailableError as exc:
        return None, str(exc)


def set_register(df, project, source_label):
    st.session_state.register = apply_scoring(df)
    st.session_state.project = project
    st.session_state.source_label = source_label
    st.session_state.retrieval = None
    st.session_state.retrieval_hash = None


def has_register():
    return st.session_state.get("register") is not None and not st.session_state.register.empty


def need_register():
    if not has_register():
        st.info("No risk register yet. Open **Project Input** to generate one, or load a sample from the sidebar.")
        return False
    return True


def run_retrieval(top_k=3):
    """Run Sentence-BERT retrieval for the whole register; cache in session state."""
    retriever, err = get_retriever()
    if retriever is None:
        st.session_state.retrieval_error = err
        return None
    st.session_state.retrieval_error = None
    df = st.session_state.register
    st.session_state.retrieval = retriever.retrieve_for_register(df, top_k=top_k)
    st.session_state.retrieval_hash = register_hash(df)
    return st.session_state.retrieval


def current_retrieval():
    """Return retrieval table only if it is still valid for the current register."""
    r = st.session_state.get("retrieval")
    if r is not None and st.session_state.get("retrieval_hash") == register_hash(st.session_state.register):
        return r
    return None


def classified_register():
    return classify_register(st.session_state.register, current_retrieval())


