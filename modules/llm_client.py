"""U2: LLM-based risk generation.

Supported free-tier providers (pick whichever key you have):
  * Google Gemini  -> GEMINI_API_KEY   (optional GEMINI_MODEL, default below)
  * Groq           -> GROQ_API_KEY     (optional GROQ_MODEL, default below)

Keys are read ONLY from environment variables or Streamlit secrets - never from code.
Every risk returned is labelled in the 'Generated By' column with the real source,
so fallback output can never be mistaken for LLM output.
"""
import json
import os
import re

import pandas as pd
import requests

from .config import LIFECYCLE_STAGES, RISK_CATEGORIES
from .lifecycle import normalise_stage
from .risk_scoring import apply_scoring, clamp_scale

GEMINI_DEFAULT_MODEL = "gemini-2.0-flash"
GROQ_DEFAULT_MODEL = "llama-3.3-70b-versatile"
REQUEST_TIMEOUT = 90


class LLMError(RuntimeError):
    """Raised when the LLM call fails or returns unusable output."""


def get_secret(name: str):
    """Look in environment variables first, then Streamlit secrets (if running in Streamlit)."""
    value = os.environ.get(name)
    if value:
        return value
    try:
        import streamlit as st
        if name in st.secrets:
            return st.secrets[name]
    except Exception:
        pass
    return None


def available_provider():
    """Return 'gemini', 'groq' or None depending on which key is configured."""
    if get_secret("GEMINI_API_KEY"):
        return "gemini"
    if get_secret("GROQ_API_KEY"):
        return "groq"
    return None


def build_prompt(project: dict, num_risks: int) -> str:
    stages = ", ".join(LIFECYCLE_STAGES)
    cats = ", ".join(RISK_CATEGORIES)
    return f"""You are an AI governance expert applying the NIST AI Risk Management Framework.
Create a project-specific AI risk register for the project below.

PROJECT NAME: {project.get('name', '')}
DESCRIPTION: {project.get('description', '')}
DOMAIN: {project.get('domain', '')}
DATA USED: {project.get('data_used', '')}
USERS / AFFECTED PEOPLE: {project.get('users', '')}
DEPLOYMENT CONTEXT: {project.get('deployment', '')}

Return ONLY a JSON array with exactly {num_risks} risks (no markdown, no commentary).
Cover every lifecycle stage at least once if possible. Each element must have these keys:
  "title": short risk title,
  "description": 1-2 sentences specific to THIS project,
  "lifecycle_stage": one of [{stages}],
  "risk_category": one of [{cats}],
  "likelihood": integer 1-5 (1 rare, 5 almost certain),
  "impact": integer 1-5 (1 negligible, 5 severe),
  "mitigation": concrete mitigation strategy,
  "stakeholder": the role responsible (e.g. Data Scientist, Clinical Lead, HR Manager, CISO).
"""


def _extract_json(text: str):
    """Pull a JSON array out of the model reply, tolerating ``` fences and extra prose."""
    text = text.strip()
    text = re.sub(r"^```(?:json)?\s*|\s*```$", "", text, flags=re.IGNORECASE).strip()
    start, end = text.find("["), text.rfind("]")
    if start == -1 or end == -1:
        raise LLMError("The model reply did not contain a JSON array.")
    try:
        return json.loads(text[start:end + 1])
    except json.JSONDecodeError as exc:
        raise LLMError(f"The model reply was not valid JSON: {exc}") from exc


def _call_gemini(prompt: str) -> str:
    key = get_secret("GEMINI_API_KEY")
    model = get_secret("GEMINI_MODEL") or GEMINI_DEFAULT_MODEL
    url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent"
    body = {
        "contents": [{"parts": [{"text": prompt}]}],
        "generationConfig": {"temperature": 0.4, "responseMimeType": "application/json"},
    }
    resp = requests.post(url, params={"key": key}, json=body, timeout=REQUEST_TIMEOUT)
    if resp.status_code != 200:
        raise LLMError(f"Gemini API error {resp.status_code}: {resp.text[:300]}")
    try:
        return resp.json()["candidates"][0]["content"]["parts"][0]["text"], f"Gemini ({model})"
    except (KeyError, IndexError) as exc:
        raise LLMError(f"Unexpected Gemini response format: {resp.text[:300]}") from exc


def _call_groq(prompt: str) -> str:
    key = get_secret("GROQ_API_KEY")
    model = get_secret("GROQ_MODEL") or GROQ_DEFAULT_MODEL
    resp = requests.post(
        "https://api.groq.com/openai/v1/chat/completions",
        headers={"Authorization": f"Bearer {key}"},
        json={"model": model, "temperature": 0.4,
              "messages": [{"role": "user", "content": prompt}]},
        timeout=REQUEST_TIMEOUT,
    )
    if resp.status_code != 200:
        raise LLMError(f"Groq API error {resp.status_code}: {resp.text[:300]}")
    try:
        return resp.json()["choices"][0]["message"]["content"], f"Groq ({model})"
    except (KeyError, IndexError) as exc:
        raise LLMError(f"Unexpected Groq response format: {resp.text[:300]}") from exc


def risks_to_dataframe(raw_risks: list, source_label: str) -> pd.DataFrame:
    """Validate and convert the model's JSON into the standard register table."""
    rows = []
    for item in raw_risks:
        if not isinstance(item, dict):
            continue
        category = item.get("risk_category", "")
        if category not in RISK_CATEGORIES:
            lowered = {c.lower(): c for c in RISK_CATEGORIES}
            category = lowered.get(str(category).strip().lower(), "Governance and Compliance")
        rows.append({
            "Title": str(item.get("title", "Untitled risk")).strip(),
            "Description": str(item.get("description", "")).strip(),
            "Lifecycle Stage": normalise_stage(item.get("lifecycle_stage", "")),
            "Risk Category": category,
            "Likelihood": clamp_scale(item.get("likelihood")),
            "Impact": clamp_scale(item.get("impact")),
            "Mitigation Strategy": str(item.get("mitigation", "")).strip(),
            "Responsible Stakeholder": str(item.get("stakeholder", "Project Manager")).strip(),
            "Generated By": source_label,
        })
    if not rows:
        raise LLMError("The model returned no usable risks.")
    df = pd.DataFrame(rows)
    df.insert(0, "Risk ID", [f"R{i:02d}" for i in range(1, len(df) + 1)])
    df["Risk Score"] = 0
    df["Severity"] = ""
    return apply_scoring(df)


def generate_risks_with_llm(project: dict, num_risks: int = 12, provider: str = None):
    """Call the configured LLM. Returns (DataFrame, source_label). Raises LLMError on failure."""
    provider = provider or available_provider()
    if provider is None:
        raise LLMError("No API key configured (set GEMINI_API_KEY or GROQ_API_KEY).")
    prompt = build_prompt(project, num_risks)
    try:
        if provider == "gemini":
            text, label = _call_gemini(prompt)
        elif provider == "groq":
            text, label = _call_groq(prompt)
        else:
            raise LLMError(f"Unknown provider '{provider}'.")
    except requests.RequestException as exc:
        raise LLMError(f"Network error while calling {provider}: {exc}") from exc
    label = f"LLM - {label}"
    return risks_to_dataframe(_extract_json(text), label), label
